#!/usr/bin/env bash
# brew-formula.sh — print the Homebrew formula for a published release.
#
# Usage:
#   scripts/brew-formula.sh v0.1.0 > Formula/mimiry.rb
#
# The formula is generated, never edited: scripts/release.sh runs this and
# pushes the result to mimiry-com/homebrew-tap. The checksums are read from the
# release's own SHA256SUMS on GitHub, so the formula can only name archives
# that were published, with the hashes they were published with.
#
# version_scheme 1: the tap's previous formula was the retired CLI, numbered
# 1.x. This CLI starts at 0.x, which Homebrew would otherwise count as older
# and never upgrade to. Raise it only if the numbering ever goes back again.

set -euo pipefail

REPO="mimiry-com/mimiry-sdk"

die() { echo "brew-formula.sh: $*" >&2; exit 1; }

version="${1:-}"
[[ "$version" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "usage: scripts/brew-formula.sh v<X.Y.Z> (got '$version')"
bare="${version#v}"
base="https://github.com/$REPO/releases/download/$version"

sums="$(curl -sSfL "$base/SHA256SUMS")" || die "could not read $base/SHA256SUMS"

sha_of() {
  local file="mimiry_${bare}_$1.tar.gz" sha
  sha="$(awk -v f="$file" '$2 == f {print $1}' <<<"$sums")"
  [[ "$sha" =~ ^[0-9a-f]{64}$ ]] || die "SHA256SUMS has no checksum for $file"
  printf '%s' "$sha"
}

darwin_amd64="$(sha_of darwin_amd64)"
darwin_arm64="$(sha_of darwin_arm64)"
linux_amd64="$(sha_of linux_amd64)"
linux_arm64="$(sha_of linux_arm64)"

cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by mimiry-sdk's scripts/brew-formula.sh for $version. Do not edit:
# the next release overwrites it.
class Mimiry < Formula
  desc "Command-line interface for the Mimiry GPU platform"
  homepage "https://github.com/$REPO"
  license "Apache-2.0"
  version_scheme 1

  on_macos do
    on_intel do
      url "$base/mimiry_${bare}_darwin_amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
    on_arm do
      url "$base/mimiry_${bare}_darwin_arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
  end

  on_linux do
    on_intel do
      url "$base/mimiry_${bare}_linux_amd64.tar.gz"
      sha256 "$linux_amd64"
    end
    on_arm do
      url "$base/mimiry_${bare}_linux_arm64.tar.gz"
      sha256 "$linux_arm64"
    end
  end

  def install
    bin.install "mimiry"
  end

  test do
    assert_match "mimiry v#{version}", shell_output("#{bin}/mimiry --version")
  end
end
EOF
